const GUARANTEE = "Гарантия до 12 месяцев на выполненные работы";

function shortName(serviceName: string): string {
  return serviceName.replace(/\s*\([^)]*\)/g, "").trim();
}

function finalize(items: string[]): string[] {
  const unique = [...new Set(items.map((item) => item.trim()).filter(Boolean))];
  const works = unique.filter((item) => item !== GUARANTEE).slice(0, 5);
  while (works.length < 5) {
    works.push("Консультация по дальнейшей эксплуатации");
  }
  return [...works.slice(0, 5), GUARANTEE];
}

